#!/usr/bin/env bash
# 11·12편 ③: 짧은 수명 인증서 발급 세 가지 — step ca certificate(JWK 토큰), ACME(lego), step ca renew(가진 인증서로 갱신)
set -uo pipefail
cd "$(dirname "$0")"; source env.sh
mkdir -p out/issued
CLI() { docker run --rm --network $NET -v "$PWD/out:/work" -w /work $STEP_CLI "$@" 2>&1 | perl -pe "s/\e\[[0-9;]*m//g"; }
COMMON="--ca-url https://ca.lab.example:9000 --root online/root.crt"
show() { openssl x509 -in "$1" -noout -subject -issuer -dates -ext subjectAltName 2>/dev/null; }

echo "== 1) step ca certificate: api.lab.example (기본 수명 24h)"
rm -f out/issued/api.*
CLI step ca certificate api.lab.example issued/api.crt issued/api.key $COMMON \
  --provisioner admin@lab.example --provisioner-password-file stepca/secrets/prov-password 2>&1
show out/issued/api.crt

echo; echo "== 2) 이름 제약 밖의 이름을 요청: shop.other.example"
CLI step ca certificate shop.other.example issued/bad.crt issued/bad.key $COMMON \
  --provisioner admin@lab.example --provisioner-password-file stepca/secrets/prov-password 2>&1 | tail -3
ls out/issued/bad.crt 2>/dev/null || echo "(bad.crt 없음)"

echo; echo "== 2b) CA 소프트웨어가 검사를 빠뜨렸다고 치고, 중간 CA 키로 openssl이 직접 서명해 보면"
openssl req -new -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -keyout out/issued/bad.key -subj "/CN=shop.other.example" -addext "subjectAltName=DNS:shop.other.example" -out out/issued/bad.csr 2>/dev/null
openssl x509 -req -in out/issued/bad.csr -CA out/online/inter.crt -CAkey out/online/inter.key -passin file:out/online/inter-pass.txt -days 1 -copy_extensions copy -out out/issued/bad.crt 2>/dev/null
openssl verify -CAfile out/online/root.crt -untrusted out/online/inter.crt out/issued/bad.crt 2>&1

echo; echo "== 3) 사슬 검증(오프라인 루트만 믿는다)"
openssl verify -CAfile out/online/root.crt -untrusted out/online/inter.crt out/issued/api.crt

echo; echo "== 4) step ca renew: 지금 인증서로 mTLS 인증해서 새 인증서를 받는다(비밀번호 없음)"
openssl x509 -in out/issued/api.crt -noout -serial
CLI step ca renew issued/api.crt issued/api.key $COMMON --force 2>&1
openssl x509 -in out/issued/api.crt -noout -serial -dates

echo; echo "== 5) ACME(HTTP-01)로 web.lab.example 발급 — 7·8편의 lego를 그대로 사내 CA에 붙인다"
rm -rf out/lego
docker run --rm --network $NET --network-alias web.lab.example -v "$PWD/out:/work" -w /work \
  -e LEGO_CA_CERTIFICATES=/work/online/root.crt $LEGO run --accept-tos --email ops@lab.example \
  --server https://ca.lab.example:9000/acme/acme/directory --path /work/lego \
  --domains web.lab.example --http --http.address :80 2>&1 | grep -vE 'HEADS UP|^$|configuration directory|backup|Your account|should make|generated by lego|server. Making'
show out/lego/certificates/web.lab.example.crt
